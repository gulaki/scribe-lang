from __future__ import annotations

from dataclasses import dataclass, field
from io import StringIO

from .ast import Binary, Block, Comparison, Expr, Goto, Grouped, If, Input, Label, Let, Number, Print, Program, Unary, Variable, While
from .semantics import SemanticModel


@dataclass
class CEmitter:
    """AST -> C backend. No parsing or semantic analysis occurs here.

    Variable declarations come from the semantic model's scopes:

    * Program-level variables become zero-initialised file-scope globals in the
      header, exactly as before blocks existed.
    * Variables first assigned inside a block are declared at the *top of the
      matching C block* as `float x = 0;`. Hoisting (rather than declaring at
      the first assignment) means a `goto` inside a block can never jump over a
      declaration, and a block-local variable starts at 0 just like a global.
    """

    indent_width: int = 4
    _header: list[str] = field(default_factory=list, init=False)
    _body: list[str] = field(default_factory=list, init=False)
    _indent: int = field(default=1, init=False)
    _model: SemanticModel | None = field(default=None, init=False)

    def emit_program(self, program: Program, model: SemanticModel) -> str:
        self._header = ["#include <stdio.h>"]
        self._body = []
        self._indent = 1
        self._model = model

        self._header.append("")
        self._header.append("/* Program-level variables generated by semantic analysis. */")
        for name in sorted(model.root.symbols):
            self._header.append(f"float {name};")
        self._header.append("")

        self._body.append("int main(void) {")
        for stmt in program.statements:
            self._stmt(stmt)
        self._body.append("    return 0;")
        self._body.append("}")
        return "\n".join(self._header + self._body) + "\n"

    def _line(self, text: str) -> None:
        self._body.append(" " * (self._indent * self.indent_width) + text)

    def _block_body(self, block: Block) -> None:
        """Emit the inside of a C block: hoisted declarations, then statements.

        The caller writes the opening and closing braces.
        """
        assert self._model is not None, "emit_program() must set the model first"
        self._indent += 1
        for name in self._model.scopes[block].symbols:
            self._line(f"float {name} = 0;")
        for child in block.statements:
            self._stmt(child)
        self._indent -= 1

    def _stmt(self, stmt) -> None:
        if isinstance(stmt, Print):
            if stmt.is_string:
                text = str(stmt.value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
                self._line(f'printf("{text}\\n");')
            else:
                self._line(f"printf(\"%.2f\\n\", (float)({self._expr(stmt.value)}));")
        elif isinstance(stmt, Input):
            self._line(f'if (scanf("%f", &{stmt.name}) != 1) {{')
            self._indent += 1
            self._line(f"{stmt.name} = 0;")
            self._line('scanf("%*s");')
            self._indent -= 1
            self._line("}")
        elif isinstance(stmt, Let):
            self._line(f"{stmt.name} = {self._expr(stmt.value)};")
        elif isinstance(stmt, If):
            self._line(f"if ({self._expr(stmt.condition)}) {{")
            self._block_body(stmt.body)
            for arm in stmt.elifs:
                self._line(f"}} else if ({self._expr(arm.condition)}) {{")
                self._block_body(arm.body)
            if stmt.orelse is not None:
                self._line("} else {")
                self._block_body(stmt.orelse)
            self._line("}")
        elif isinstance(stmt, While):
            self._line(f"while ({self._expr(stmt.condition)}) {{")
            self._block_body(stmt.body)
            self._line("}")
        elif isinstance(stmt, Block):
            self._line("{")
            self._block_body(stmt)
            self._line("}")
        elif isinstance(stmt, Label):
            # Labels need special indentation in C. The trailing `;` is a null
            # statement: C11 requires a statement after a label, so without it
            # a label that ends a block is rejected by strict compilers.
            self._body.append(f"{stmt.name}:;")
        elif isinstance(stmt, Goto):
            self._line(f"goto {stmt.name};")

    def _expr(self, expr: Expr) -> str:
        if isinstance(expr, Number):
            return expr.value
        if isinstance(expr, Variable):
            return expr.name
        if isinstance(expr, Grouped):
            return self._expr(expr.value)
        if isinstance(expr, Unary):
            return f"({expr.operator}{self._expr(expr.operand)})"
        if isinstance(expr, Binary):
            return f"({self._expr(expr.left)} {expr.operator} {self._expr(expr.right)})"
        if isinstance(expr, Comparison):
            return f"({self._expr(expr.left)} {expr.operator} {self._expr(expr.right)})"
        raise TypeError(f"Unsupported expression node: {type(expr).__name__}")
